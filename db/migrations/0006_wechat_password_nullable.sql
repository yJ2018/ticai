-- ============================================================================
-- 0006：微信建的账号没有密码
--
-- 微信首次登录只能拿到 openid / unionid / 昵称 / 头像，没有邮箱也没有密码。
-- 这类账号的 password_hash 必须允许为空；密码登录时 verifyPassword 会直接返回 false。
-- ============================================================================

alter table app_user alter column password_hash drop not null;
